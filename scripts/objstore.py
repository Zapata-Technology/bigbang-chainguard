"""Object storage for Big Bang: SeaweedFS (default) or Big Bang's own MinIO.

The OBJECT_STORAGE setting (--object-storage, $OBJECT_STORAGE, or the OBJECT_STORAGE
file) picks one:

  seaweedfs  bb-convert.py writes overlays/values-object-storage.yaml, which turns every
             MinIO off and points each package that can use S3 at OBJECT_STORAGE_ENDPOINT
             (default: the in-cluster SeaweedFS below), and seaweedfs/ + seaweedfs-fips/,
             kustomizations that run SeaweedFS from the org's image and create the
             buckets the overlay names.
  minio      none of that: Big Bang deploys MinIO itself, on Chainguard's minio images.

object-storage.yaml records where each Big Bang package takes its S3 settings.
"""
import json
import os
import urllib.parse

import yaml

from bbcommon import ROOT, deep_merge, setting

KINDS = ("seaweedfs", "minio")
NAMESPACE = "seaweedfs"
DEFAULT_ENDPOINT = f"http://seaweedfs-s3.{NAMESPACE}.svc.cluster.local:8333"
MINIO_SERVERS = ("ironbank/opensource/minio/minio", "ironbank/opensource/minio/operator",
                 "ironbank/opensource/minio/operator-sidecar")


def kind(arg=None):
    """The OBJECT_STORAGE setting: seaweedfs (default) or minio."""
    value = (setting("OBJECT_STORAGE", arg) or "seaweedfs").lower()
    if value not in KINDS:
        raise SystemExit(f"OBJECT_STORAGE must be one of {', '.join(KINDS)}, not {value!r}")
    return value


def endpoint(arg=None):
    return setting("OBJECT_STORAGE_ENDPOINT", arg) or DEFAULT_ENDPOINT


def tokens(url, region, prefix):
    u = urllib.parse.urlparse(url)
    if u.scheme not in ("http", "https") or not u.netloc:
        raise SystemExit(f"--endpoint must be http(s)://host[:port], not {url!r}")
    return {"endpoint": url.rstrip("/"), "host": u.netloc, "region": region, "prefix": prefix,
            "insecure": u.scheme == "http"}


def fill(value, t):
    """Replace the {tokens} in a value tree; a value that is exactly "{insecure}" becomes a boolean."""
    if isinstance(value, dict):
        return {k: fill(v, t) for k, v in value.items()}
    if isinstance(value, list):
        return [fill(v, t) for v in value]
    if not isinstance(value, str):
        return value
    if value == "{insecure}":
        return t["insecure"]
    out = value
    while "{bucket:" in out:
        start = out.index("{bucket:")
        end = out.index("}", start)
        out = out[:start] + f"{t['prefix']}-{out[start + 8:end]}" + out[end + 1:]
    for k in ("endpoint", "host", "region", "prefix"):
        out = out.replace("{" + k + "}", str(t[k]))
    return out


def set_dotted(tree, dotted, value):
    keys = dotted.split(".")
    for k in keys[:-1]:
        tree = tree.setdefault(k, {})
    if isinstance(value, dict) and isinstance(tree.get(keys[-1]), dict):
        deep_merge(tree[keys[-1]], value)
    else:
        tree[keys[-1]] = value


def load_spec(path=None):
    return yaml.safe_load(open(path or os.path.join(ROOT, "object-storage.yaml")))


def build(spec, t, extra):
    """(overlay, credential value paths, buckets, packages) for the chosen packages."""
    overlay, creds, buckets, chosen = {}, [], [], []
    for dotted, v in spec.get("disable", {}).items():
        set_dotted(overlay, dotted, v)
    for name, pkg in spec["packages"].items():
        if pkg.get("optional") and name not in extra:
            continue
        chosen.append(name)
        for dotted, v in pkg["values"].items():
            set_dotted(overlay, dotted, fill(v, t))
        creds += pkg.get("credentials", [])
        buckets += [f"{t['prefix']}-{b}" for b in pkg.get("buckets", [])]
    return overlay, creds, buckets, chosen


def credentials_template(paths, access="<access key>", secret="<secret key>"):
    """The credential values a site file sets; Velero's takes an AWS credentials file."""
    tree = {}
    for p in paths:
        if p.endswith(".cloud"):
            value = f"[default]\naws_access_key_id={access}\naws_secret_access_key={secret}\n"
        else:
            value = access if p.endswith("accessKey") else secret
        set_dotted(tree, p, value)
    return tree


def overlay_text(overlay, t, chosen, generator):
    return (f"# GENERATED by {generator} from object-storage.yaml - do not edit by hand.\n"
            f"# S3 object storage at {t['endpoint']} instead of MinIO, for: {', '.join(chosen)}.\n"
            "# Layer it after the Chainguard overlays; credentials go in the site file:\n"
            "# ... -f overlays/values-chainguard.yaml -f overlays/values-object-storage.yaml -f <site>.yaml\n"
            + yaml.safe_dump(overlay, sort_keys=True, default_flow_style=False, width=120))


def seaweedfs_files(image, dev_image, buckets, header):
    """seaweedfs/ kustomization: one SeaweedFS server (master, volume, filer, S3) on a
    PersistentVolumeClaim, S3 authentication from the seaweedfs-s3 Secret, and a Job that
    creates the buckets. The namespace's private-registry and seaweedfs-s3 Secrets are
    the site's to create (README)."""
    labels = {"app.kubernetes.io/name": "seaweedfs"}
    pod_security = {"runAsNonRoot": True, "runAsUser": 65532, "runAsGroup": 65532, "fsGroup": 65532,
                    "seccompProfile": {"type": "RuntimeDefault"}}
    container_security = {"allowPrivilegeEscalation": False, "capabilities": {"drop": ["ALL"]}}
    script = ("set -e\n"
              "until printf 'cluster.check\\n' | weed shell -master=seaweedfs:9333 -filer=seaweedfs:8888 >/dev/null 2>&1; "
              "do echo waiting for seaweedfs; sleep 5; done\n"
              + "".join(f"printf 's3.bucket.create -name {b}\\n' | weed shell -master=seaweedfs:9333 -filer=seaweedfs:8888\n"
                        for b in buckets)
              + "printf 's3.bucket.list\\n' | weed shell -master=seaweedfs:9333 -filer=seaweedfs:8888\n")
    docs = [
        {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": NAMESPACE}},
        {"apiVersion": "v1", "kind": "PersistentVolumeClaim", "metadata": {"name": "seaweedfs-data"},
         "spec": {"accessModes": ["ReadWriteOnce"], "resources": {"requests": {"storage": "50Gi"}}}},
        {"apiVersion": "apps/v1", "kind": "Deployment", "metadata": {"name": "seaweedfs", "labels": labels},
         "spec": {"replicas": 1, "strategy": {"type": "Recreate"}, "selector": {"matchLabels": labels},
                  "template": {"metadata": {"labels": labels}, "spec": {
                      "imagePullSecrets": [{"name": "private-registry"}],
                      "securityContext": pod_security,
                      "containers": [{
                          "name": "seaweedfs", "image": image,
                          "args": ["server", "-dir=/data", "-ip.bind=0.0.0.0", "-master.volumeSizeLimitMB=1024",
                                   "-volume.max=0", "-s3", "-s3.port=8333", "-s3.config=/etc/seaweedfs/s3.json"],
                          "ports": [{"name": p, "containerPort": n} for p, n in
                                    (("s3", 8333), ("master", 9333), ("master-grpc", 19333),
                                     ("filer", 8888), ("filer-grpc", 18888), ("volume", 8080))],
                          "readinessProbe": {"tcpSocket": {"port": 8333}, "periodSeconds": 5},
                          "resources": {"requests": {"cpu": "100m", "memory": "256Mi"}},
                          "securityContext": container_security,
                          "volumeMounts": [{"name": "data", "mountPath": "/data"},
                                           {"name": "s3-config", "mountPath": "/etc/seaweedfs", "readOnly": True}]}],
                      "volumes": [{"name": "data", "persistentVolumeClaim": {"claimName": "seaweedfs-data"}},
                                  {"name": "s3-config", "secret": {"secretName": "seaweedfs-s3"}}]}}}},
        {"apiVersion": "v1", "kind": "Service", "metadata": {"name": "seaweedfs-s3"},
         "spec": {"selector": labels, "ports": [{"name": "s3", "port": 8333}]}},
        # master + filer for weed shell (the bucket Job); not for clients.
        {"apiVersion": "v1", "kind": "Service", "metadata": {"name": "seaweedfs"},
         "spec": {"selector": labels, "ports": [{"name": p, "port": n} for p, n in
                                                (("master", 9333), ("master-grpc", 19333),
                                                 ("filer", 8888), ("filer-grpc", 18888))]}},
        {"apiVersion": "batch/v1", "kind": "Job", "metadata": {"name": "seaweedfs-buckets"},
         "spec": {"backoffLimit": 10, "template": {"spec": {
             "restartPolicy": "OnFailure",
             "imagePullSecrets": [{"name": "private-registry"}],
             "securityContext": pod_security,
             "containers": [{"name": "buckets", "image": dev_image, "command": ["/bin/sh", "-c", script],
                             "securityContext": container_security}]}}}},
    ]
    return {
        "kustomization.yaml": header + yaml.safe_dump({
            "apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
            "namespace": NAMESPACE, "resources": ["seaweedfs.yaml"]}, sort_keys=False),
        "seaweedfs.yaml": header + yaml.safe_dump_all(docs, sort_keys=False, width=200),
    }


def s3_config(access, secret):
    """SeaweedFS's s3.json: one identity with the given keys, allowed everything."""
    return json.dumps({"identities": [{"name": "bigbang", "credentials": [{"accessKey": access, "secretKey": secret}],
                                       "actions": ["Admin", "Read", "List", "Tagging", "Write"]}]}, indent=2)
