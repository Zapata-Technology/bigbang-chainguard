#!/usr/bin/env python3
"""Keep docs/testing.md's kind-test results table generated from recorded compat.yml runs,
so nobody hand-edits run IDs and dates that then go stale.

  test-results.py record --test loki --mode fips --outcome success --log compat.log --out results/
      one compat.yml job: write its result as JSON (test, mode, pass/fail, Big Bang
      version, when, run, commit) for the job's `compat-result-<test>-<mode>` artifact
  test-results.py update [--results DIR ...] [--from-main N] [--run ID]
      merge new results into docs/test-results.json (the newest per test and mode wins) and
      rewrite the table between docs/testing.md's results markers; prose outside them is
      left alone. --from-main downloads the result artifacts of the last N completed
      compat.yml runs on main (`gh`); --run those of one run.
  test-results.py summary --results DIR     the results in DIR as a Markdown table
  test-results.py check                     exit 1 if docs/testing.md's table isn't what
                                            docs/test-results.json renders

docs/test-results.json holds each test's description ("tests": edit those there) and the
newest result per test and mode ("results": written by this script). A test with no new
run keeps its recorded result and row. update.yml runs `update --from-main` nightly and
puts both files in its bot pull request.
"""
import argparse
import datetime
import glob
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "docs", "test-results.json")
DOC = os.path.join(ROOT, "docs", "testing.md")
START, END = "<!-- results:start -->", "<!-- results:end -->"
HEADER = ("<!-- GENERATED by scripts/test-results.py from docs/test-results.json: edit a test's "
          "description there; results come from compat.yml runs. Don't edit this table. -->")
MODES = ("standard", "fips")
# A cancelled or timed-out job, or one whose setup failed, says nothing about the package:
# it is recorded as `error` and never replaces a real result.
RESULTS = ("pass", "fail", "skipped")
ARTIFACTS = "compat-result*"   # each job's compat-result-<test>-<mode>, and compat-results


# --- one job's result ---

def outcome_result(outcome, log_text):
    """A compat.yml job's result from its "Deploy and check" step outcome and compat.log."""
    if outcome == "success":
        # A registry1 test without an Iron Bank login exits 0 but tested nothing.
        return "skipped" if re.search(r"^RESULT .*: SKIPPED", log_text, re.M) else "pass"
    return "fail" if outcome == "failure" else "error"


def record(test, mode, outcome, log_text, env, bigbang, now=None, preview=False):
    """The JSON a job uploads; env is the job's GITHUB_* environment. `preview`: the job
    deployed a Big Bang branch (compat.yml's bigbang_ref), not BIGBANG_VERSION."""
    now = now or datetime.datetime.now(datetime.timezone.utc)
    run_id = env.get("GITHUB_RUN_ID", "")
    server, repo = env.get("GITHUB_SERVER_URL", "https://github.com"), env.get("GITHUB_REPOSITORY", "")
    return ({"preview": True} if preview else {}) | {
        "test": test, "mode": mode, "result": outcome_result(outcome, log_text),
        "bigbang": bigbang, "finished": now.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "run_id": int(run_id) if run_id.isdigit() else run_id,
        "run_attempt": int(env.get("GITHUB_RUN_ATTEMPT", "1") or 1),
        "run_url": f"{server}/{repo}/actions/runs/{run_id}" if repo and run_id else "",
        "commit": env.get("GITHUB_SHA", ""), "event": env.get("GITHUB_EVENT_NAME", ""),
        "branch": env.get("GITHUB_REF_NAME", ""),
    }


# --- merging ---

def valid(r):
    return (isinstance(r, dict) and isinstance(r.get("test"), str) and r.get("mode") in MODES
            and r.get("result") in RESULTS and isinstance(r.get("finished"), str))


def number(value, default=0):
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def order(r):
    """Newer sorts later: when it finished, then the run and its attempt."""
    return (r["finished"], number(r.get("run_id")), number(r.get("run_attempt"), 1))


def merge(old, new):
    """The newest valid result per (test, mode), old and new together, sorted. A preview
    result (a Big Bang branch before its release, from bigbang-preview.yml) describes what
    is coming, not what this repo deploys: it never enters the table."""
    best = {}
    for r in list(old) + list(new):
        if not valid(r) or r.get("preview"):
            continue
        key = (r["test"], r["mode"])
        if key not in best or order(r) > order(best[key]):
            best[key] = r
    return [best[k] for k in sorted(best)]


def read_dir(path):
    """Every result JSON under path (artifacts unpack into one directory each)."""
    found = []
    for f in sorted(glob.glob(os.path.join(path, "**", "*.json"), recursive=True)):
        try:
            doc = json.load(open(f, encoding="utf-8"))
        except (OSError, ValueError) as e:
            print(f"skipping {f}: {e}", file=sys.stderr)
            continue
        for r in doc if isinstance(doc, list) else [doc]:
            if valid(r):
                found.append(r)
            else:
                print(f"skipping {f}: not a result", file=sys.stderr)
    return found


# --- downloading (gh) ---

def gh(*args):
    p = subprocess.run(["gh", *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    return p.returncode, p.stdout, p.stderr


def repo_args():
    repo = os.environ.get("GITHUB_REPOSITORY")
    return ["-R", repo] if repo else []


def main_runs(limit):
    """The last completed compat.yml runs on main (schedule and manual; not pull requests)."""
    rc, out, err = gh("run", "list", *repo_args(), "--workflow", "compat.yml", "--branch", "main",
                      "--status", "completed", "-L", str(limit), "--json", "databaseId,event")
    if rc:
        raise SystemExit(f"gh run list failed: {err.strip()}")
    return [r["databaseId"] for r in json.loads(out) if r.get("event") != "pull_request"]


def download(run, dest):
    """A run's result artifacts into dest; a run from before results were recorded has none."""
    rc, _, err = gh("run", "download", str(run), *repo_args(), "--pattern", ARTIFACTS, "-D", dest)
    if rc and "no valid artifacts" not in err and "no artifact" not in err.lower():
        print(f"run {run}: {err.strip()}", file=sys.stderr)
    return read_dir(dest) if os.path.isdir(dest) else []


# --- rendering ---

def large(test, root=ROOT):
    path = os.path.join(root, "compat", f"{test}.yaml")
    return os.path.exists(path) and bool(re.search(r"^  large: true", open(path, encoding="utf-8").read(), re.M))


def cell(r):
    if not r:
        return "no run recorded"
    return f"**{r['result'].upper()}** on {r['bigbang']}, {r['finished'][:10]}" + (
        f" ([run {r['run_id']}]({r['run_url']}))" if r.get("run_url") else "")


def table(data, root=ROOT):
    """The generated block, markers excluded: described tests in their order, then any
    other test that has a result."""
    results = {(r["test"], r["mode"]): r for r in data.get("results", [])}
    described = [t["test"] for t in data.get("tests", [])]
    about = {t["test"]: t for t in data.get("tests", [])}
    names = described + sorted({t for t, _ in results} - set(described))
    lines = [HEADER, "", "| Test | What runs | Standard | FIPS | Notes |", "|---|---|---|---|---|"]
    for name in names:
        t = about.get(name, {})
        label = name + (" (large)" if large(name, root) else "")
        lines.append(f"| {label} | {t.get('runs') or '-'} | {cell(results.get((name, 'standard')))} "
                     f"| {cell(results.get((name, 'fips')))} | {t.get('notes') or '-'} |")
    return "\n".join(lines)


def section(text):
    """(before, inside, after) of the marked block; inside excludes the markers."""
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise SystemExit(f"docs/testing.md needs {START} and {END} around the results table")
    return text[:i + len(START)], text[i + len(START):j], text[j:]


def replace(text, block):
    """text with the marked block replaced, everything outside it unchanged (CRLF kept)."""
    nl = "\r\n" if "\r\n" in text else "\n"
    before, _, after = section(text)
    return before + nl + block.replace("\n", nl) + nl + after


def current(text):
    return section(text)[1].replace("\r\n", "\n").strip("\n")


def summary(results):
    lines = ["| Test | Mode | Result | Big Bang | Finished |", "|---|---|---|---|---|"]
    lines += [f"| {r['test']} | {r['mode']} | {r['result'].upper()} | {r['bigbang']} | {r['finished']} |"
              for r in sorted(results, key=lambda r: (r["test"], r["mode"]))]
    return "\n".join(lines)


# --- files ---

def load(path=None):
    return json.load(open(path or DATA, encoding="utf-8"))


def save(data, path=None):
    with open(path or DATA, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def read_text(path):
    with open(path, encoding="utf-8", newline="") as f:
        return f.read()


def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    rec = sub.add_parser("record")
    rec.add_argument("--test", required=True)
    rec.add_argument("--mode", required=True, choices=MODES)
    rec.add_argument("--outcome", required=True, help="the Deploy and check step's outcome")
    rec.add_argument("--log", help="the job's compat.log")
    rec.add_argument("--out", required=True, help="directory for <test>-<mode>.json")
    rec.add_argument("--preview", action="store_true",
                     help="the job deployed a Big Bang branch (bigbang_ref): kept out of the table")
    up = sub.add_parser("update")
    up.add_argument("--results", action="append", default=[], help="a directory of result JSONs")
    up.add_argument("--from-main", type=int, metavar="N", help="the last N compat.yml runs on main")
    up.add_argument("--run", action="append", default=[], help="one compat.yml run's results")
    sm = sub.add_parser("summary")
    sm.add_argument("--results", required=True)
    sub.add_parser("check")
    a = ap.parse_args()

    if a.cmd == "record":
        log = read_text(a.log) if a.log and os.path.exists(a.log) else ""
        bigbang = open(os.path.join(ROOT, "BIGBANG_VERSION"), encoding="utf-8").read().strip()
        r = record(a.test, a.mode, a.outcome, log, os.environ, bigbang, preview=a.preview)
        os.makedirs(a.out, exist_ok=True)
        save(r, os.path.join(a.out, f"{a.test}-{a.mode}.json"))
        print(json.dumps(r))
        return 0
    if a.cmd == "summary":
        print(summary(read_dir(a.results)))
        return 0
    data = load()
    if a.cmd == "check":
        if current(read_text(DOC)) != table(data):
            print("docs/testing.md's results table isn't what docs/test-results.json renders: "
                  "run scripts/test-results.py update", file=sys.stderr)
            return 1
        return 0

    new = []
    for d in a.results:
        new += read_dir(d)
    runs = list(a.run) + (main_runs(a.from_main) if a.from_main else [])
    with tempfile.TemporaryDirectory() as tmp:
        for run in runs:
            got = download(run, os.path.join(tmp, str(run)))
            # Only main's own runs count when downloading from main.
            new += [r for r in got if not a.from_main or r.get("branch") in ("main", "")]
    before = {(r["test"], r["mode"]): r for r in data.get("results", [])}
    data["results"] = merge(data.get("results", []), new)
    changed = [r for r in data["results"] if before.get((r["test"], r["mode"])) != r]
    save(data)
    write_text(DOC, replace(read_text(DOC), table(data)))
    print(f"{len(new)} result(s) read, {len(changed)} newer than recorded")
    for r in changed:
        print(f"  {r['test']} ({r['mode']}): {r['result']} on {r['bigbang']}, {r['finished']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
