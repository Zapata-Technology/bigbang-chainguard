#!/usr/bin/env python3
"""Upgrade notes for a new Big Bang release: what changes between the release main deploys
and the new one, as docs/upgrades/<new>.md (update.yml's release PR carries it and puts it
in the PR body, so whoever merges reads it first, and sites read it before upgrading).

  bb-release-notes.py --from 4.0.0 --to 4.1.0 --old-images OLD.json [--new-images discovery/images.json]
                      [--old-values OLD-values.yaml] [--new-values work/bigbang/chart/values.yaml]
                      [-o docs/upgrades/4.1.0.md]

It lists:
  - packages added to or removed from Big Bang, and each package whose chart tag moved
    (from Big Bang's chart/values.yaml at both releases; --old-values, else fetched from
    repo1.dso.mil; skipped with a note when neither works)
  - each Iron Bank image whose tag moved, appeared or went away, per package (from
    discovery/images.json at both releases: main's, and the one this run discovered)
  - links to Big Bang's release page and changelog

It doesn't judge the changes: the release PR's report (bb-convert, bb-verify, bb-scan) and
its kind tests say whether this repo handles them.
"""
import argparse
import json
import os
import re
import sys
import time
import urllib.request

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bbcommon import ROOT, bigbang_packages  # noqa: E402

REPO1 = "https://repo1.dso.mil/big-bang/bigbang"


def chart_tags(values):
    """{package key: chart git tag} from Big Bang's chart/values.yaml."""
    if not values:
        return {}
    return {k: str((x.get("git") or {}).get("tag") or (x.get("helmRepo") or {}).get("tag") or "")
            for k, x in bigbang_packages(values).items()}


def split_ref(ref):
    """registry/path:tag -> (path, tag), the registry dropped (it is registry1 in both)."""
    ref = ref.split("@", 1)[0]
    name, _, tag = ref.rpartition(":")
    if not name or "/" in tag:
        name, tag = ref, ""
    return name.split("/", 1)[1] if "." in name.split("/", 1)[0] else name, tag


def images(discovered):
    """{package: {image path: sorted tags}} from discovery/images.json."""
    out = {}
    for pkg, p in (discovered or {}).get("packages", {}).items():
        found = {}
        for ref in p.get("rendered", []):
            path, tag = split_ref(ref)
            found.setdefault(path, set()).add(tag)
        out[pkg] = {k: sorted(v) for k, v in found.items()}
    return out


def major(version):
    """A version's major number ("v19.5.3-ubi" -> 19, "ubi-fips-v19.5.2" -> 19), or None."""
    m = re.search(r"(\d+)\.\d+", version or "")
    return int(m.group(1)) if m else None


def majors(old, new):
    """Packages whose chart moves to a new major version: their upgrade notes come first."""
    return [f"{k.split('.', 1)[-1]} {old[k]} -> {new[k]}" for k in sorted(set(old) & set(new))
            if major(old[k]) is not None and major(new[k]) is not None and major(old[k]) != major(new[k])]


def diff_charts(old, new):
    rows = []
    for k in sorted(set(old) | set(new)):
        a, b = old.get(k), new.get(k)
        if a == b:
            continue
        name = k.split(".", 1)[-1]
        if a is None:
            rows.append(f"| {name} | added | {b} |")
        elif b is None:
            rows.append(f"| {name} | {a} | removed |")
        else:
            rows.append(f"| {name} | {a} | {b} |")
    return rows


def diff_images(old, new):
    rows = []
    for pkg in sorted(set(old) | set(new)):
        a, b = old.get(pkg, {}), new.get(pkg, {})
        for path in sorted(set(a) | set(b)):
            ta, tb = a.get(path), b.get(path)
            if ta == tb:
                continue
            fa = ", ".join(ta) if ta else "(new)"
            fb = ", ".join(tb) if tb else "(gone)"
            rows.append(f"| {pkg} | `{path}` | {fa} | {fb} |")
    return rows


def fetch_values(version, attempts=3):
    """Big Bang's chart/values.yaml at a release, or None (repo1 refuses runners at times)."""
    url = f"{REPO1}/-/raw/{version}/chart/values.yaml"
    for i in range(attempts):
        try:
            with urllib.request.urlopen(url, timeout=60) as r:
                return yaml.safe_load(r.read())
        except Exception as e:  # noqa: BLE001 - any failure: retry, then go without
            err = e
            if i < attempts - 1:
                time.sleep(20 * (i + 1))
    print(f"warning: couldn't read Big Bang {version}'s values ({err}); no chart table", file=sys.stderr)
    return None


def notes(old_version, new_version, old_values, new_values, old_images, new_images):
    lines = [f"# Upgrading from Big Bang {old_version} to {new_version}", "",
             "Generated by `scripts/bb-release-notes.py` in the nightly release pull request.",
             "",
             f"Big Bang's own notes: [release {new_version}]({REPO1}/-/releases/{new_version}),",
             f"[CHANGELOG]({REPO1}/-/blob/{new_version}/CHANGELOG.md). Read them for value",
             "changes your site's values may need; this page lists what moves underneath.", ""]
    lines += ["## Package charts", ""]
    if old_values is None or new_values is None:
        lines += ["Not listed: Big Bang's values at one of the releases couldn't be read.", ""]
    else:
        old_tags, new_tags = chart_tags(old_values), chart_tags(new_values)
        big = majors(old_tags, new_tags)
        if big:
            lines += ["New major chart versions (read their packages' upgrade notes first):", ""]
            lines += [f"- {x}" for x in big] + [""]
        rows = diff_charts(old_tags, new_tags)
        lines += (["| Package | " + old_version + " | " + new_version + " |", "|---|---|---|"] + rows
                  if rows else ["No package chart moved."]) + [""]
    lines += ["## Iron Bank images", "",
              "The images Big Bang deploys (before this repo maps them to the org's).", ""]
    rows = diff_images(images(old_images), images(new_images))
    lines += (["| Package | Image | " + old_version + " | " + new_version + " |", "|---|---|---|---|"] + rows
              if rows else ["No image moved."]) + [""]
    lines += ["## Upgrading a site", "",
              "Re-run `python scripts/bb-install.py install` from a checkout of the release tag",
              "(`" + new_version + "-cg.N`); `bb-install.py status` says when a cluster is behind.",
              "Take a backup first where Velero is enabled (docs/install.md, \"Upgrading\").", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="old", required=True)
    ap.add_argument("--to", dest="new", required=True)
    ap.add_argument("--old-images", required=True)
    ap.add_argument("--new-images", default=os.path.join(ROOT, "discovery", "images.json"))
    ap.add_argument("--old-values")
    ap.add_argument("--new-values", default=os.path.join(ROOT, "work", "bigbang", "chart", "values.yaml"))
    ap.add_argument("-o", "--out")
    a = ap.parse_args(argv)

    def load(path, parse):
        try:
            with open(path, encoding="utf-8") as f:
                return parse(f)
        except (OSError, ValueError, yaml.YAMLError) as e:
            print(f"warning: {path}: {e}", file=sys.stderr)
            return None

    old_values = load(a.old_values, yaml.safe_load) if a.old_values else fetch_values(a.old)
    new_values = load(a.new_values, yaml.safe_load)
    text = notes(a.old, a.new, old_values, new_values,
                 load(a.old_images, json.load), load(a.new_images, json.load))
    if a.out:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        with open(a.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(text)


if __name__ == "__main__":
    main()
