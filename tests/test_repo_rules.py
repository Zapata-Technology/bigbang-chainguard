# --- mapping.yaml is validated, so a typo fails instead of silently doing nothing ---

def test_real_mapping_org_files_and_compat_overlays_are_valid():
    for org_file in glob.glob(os.path.join(ROOT, "orgs", "*.yaml")):
        org = os.path.basename(org_file)[:-5]
        bbcommon.load_mapping(org, overlays=sorted(glob.glob(os.path.join(ROOT, "compat", "*.yaml"))))


@pytest.mark.parametrize("bad, message", [
    ({"images": {}, "imgaes": {}}, "unknown section 'imgaes'"),
    ({"images": {"ib/x": {"cg": "x", "fipz": None}}}, "unknown option 'fipz'"),
    ({"images": {"ib/x": {"cg": "x", "strict": "yes"}}}, "strict: 'yes' has the wrong type"),
    ({"images": {"ib/x": {"fallback": "ironbank"}}}, "needs one of"),
    ({"images": {"ib/x": {"cg": "x", "fallback": "chainguard"}}}, "only 'ironbank'"),
    ({"images": {"ib/x": ["x"]}}, "expected a Chainguard name"),
    ({"images": {}, "bash_commands": {"pkg": [{"kind": "Job", "name": "j"}]}}, "kind, name, container"),
])
def test_validate_mapping_rejects(bad, message):
    with pytest.raises(ValueError, match=re.escape(message)):
        bbcommon.validate_mapping(bad)


def test_every_mapping_section_is_documented_in_mapping_yaml_and_used_by_code():
    mapping_text = open(os.path.join(ROOT, "mapping.yaml"), encoding="utf-8").read()
    code = "\n".join(open(p, encoding="utf-8").read() for p in glob.glob(os.path.join(ROOT, "scripts", "*.py")))
    for section in bbcommon.MAPPING_SECTIONS:
        assert re.search(rf"^{section}:", mapping_text, re.M), f"{section} has no block in mapping.yaml"
        assert f'"{section}"' in code.replace(f'"{section}"}}', f'"{section}"'), f"no script reads {section}"


# --- generated files are never hand-edited ---

GENERATED = ["overlays/values-chainguard.yaml", "overlays/values-chainguard-fips.yaml",
             "overlays/values-object-storage.yaml", "flux/kustomization.yaml", "flux-fips/kustomization.yaml",
             "docs/images.md", "docs/required-images.md", "seaweedfs/kustomization.yaml",
             "seaweedfs-fips/kustomization.yaml"] + \
            [os.path.relpath(p, ROOT).replace(os.sep, "/") for p in glob.glob(os.path.join(ROOT, "builds", "*", "build.yaml"))]


@pytest.mark.parametrize("rel", GENERATED)
def test_generated_files_say_so(rel):
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        pytest.skip(f"{rel} not generated in this checkout")
    head = open(path, encoding="utf-8").read(600)
    assert re.search(r"GENERATED by `?scripts/[\w.-]+", head, re.I), f"{rel} lost its GENERATED header"


# --- workflows: every action pinned to a full commit SHA, every job has a timeout or is short ---

WORKFLOWS = sorted(glob.glob(os.path.join(ROOT, ".github", "workflows", "*.yml")))


@pytest.mark.parametrize("path", WORKFLOWS, ids=os.path.basename)
def test_actions_are_pinned_to_commit_shas(path):
    for line in open(path, encoding="utf-8"):
        m = re.search(r"uses:\s*([^\s#]+)", line)
        if not m or m.group(1).startswith("./"):
            continue
        ref = m.group(1).split("@")
        assert len(ref) == 2 and re.fullmatch(r"[0-9a-f]{40}", ref[1]), f"not SHA-pinned: {m.group(1)}"
        assert "#" in line, f"add the version as a comment: {line.strip()}"


@pytest.mark.parametrize("path", WORKFLOWS, ids=os.path.basename)
def test_workflows_parse_and_declare_permissions(path):
    doc = yaml.safe_load(open(path, encoding="utf-8"))
    assert "permissions" in doc, "top-level permissions keep the default token least-privilege"


# --- scripts explain themselves ---

@pytest.mark.parametrize("path", sorted(glob.glob(os.path.join(ROOT, "scripts", "*.py"))), ids=os.path.basename)
def test_every_script_has_a_module_docstring(path):
    tree = ast.parse(open(path, encoding="utf-8").read())
    doc = ast.get_docstring(tree)
    assert doc and len(doc) > 40, "start each script with what it does and how to run it"


# --- docs don't point at files that no longer exist ---

DOCS = [os.path.join(ROOT, f) for f in ("AGENTS.md", "README.md", "CONTRIBUTING.md", "SECURITY.md")] + \
    sorted(glob.glob(os.path.join(ROOT, "docs", "*.md")))


@pytest.mark.parametrize("path", DOCS, ids=lambda p: os.path.relpath(p, ROOT))
def test_docs_reference_existing_files(path):
    text = open(path, encoding="utf-8").read()
    base = os.path.dirname(path)
    missing = []
    for link in re.findall(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", text):
        if not re.match(r"[a-z]+:", link) and not os.path.exists(os.path.join(base, link)):
            missing.append(link)
    for script in set(re.findall(r"\bscripts/([\w-]+\.py)\b", text)):
        if not os.path.exists(os.path.join(ROOT, "scripts", script)):
            missing.append(f"scripts/{script}")
    assert not missing, f"{os.path.basename(path)} references missing files: {missing}"


# --- hand-written docs quote generated counts; they must agree ---

def test_readme_iron_bank_count_matches_docs_images():
    images = open(os.path.join(ROOT, "docs", "images.md"), encoding="utf-8").read()
    readme = open(os.path.join(ROOT, "README.md"), encoding="utf-8").read()
    generated = re.search(r"^## Stays on Iron Bank \((\d+)\)", images, re.M).group(1)
    quoted = re.findall(r"(\d+) images stay on Iron Bank", readme)
    assert quoted and set(quoted) == {generated}, f"README says {quoted}, docs/images.md says {generated}"


def test_readme_lists_every_image_built_here():
    readme = open(os.path.join(ROOT, "README.md"), encoding="utf-8").read()
    for d in glob.glob(os.path.join(ROOT, "builds", "*", "Dockerfile")):
        name = os.path.basename(os.path.dirname(d))
        if name == "installer":
            continue   # the installer image has its own README section
        assert f"`bigbang-{name}`" in readme, f"README's 'Images this repo builds' has no bigbang-{name}"
