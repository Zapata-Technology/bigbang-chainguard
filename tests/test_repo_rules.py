@pytest.mark.parametrize("rel", GENERATED)
def test_generated_files_say_so(rel):
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        pytest.skip(f"{rel} not generated in this checkout")
    head = open(path, encoding="utf-8").read(600)
    assert re.search(r"GENERATED by `?scripts/[\w.-]+", head, re.I), f"{rel} lost its GENERATED header"


ORG_FILES = GENERATED + ["seaweedfs/seaweedfs.yaml", "seaweedfs-fips/seaweedfs.yaml"]


@pytest.mark.parametrize("rel", ORG_FILES)
def test_generated_files_that_name_an_org_say_how_to_regenerate(rel):
    # The committed files are generated for one org; whoever copies the repo must see, at the
    # top, that theirs come from re-running the pipeline (bb-convert.org_note).
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        pytest.skip(f"{rel} not generated in this checkout")
    text = open(path, encoding="utf-8").read()
    if not re.search(r"cgr\.dev/[\w.-]+/", text):
        return
    assert re.search(r"Generated for `?cgr\.dev/[\w.-]+`?: for another org, regenerate it with "
                     r"python scripts/bb-run\.py --org", text[:1500]), f"{rel} doesn't say how another org regenerates it"


# Partly generated: only the block between the markers. It must say so, and be exactly what
# its data file renders, so a hand edit of the table fails here.
PARTLY_GENERATED = {"docs/testing.md": "test-results"}


@pytest.mark.parametrize("rel, script", PARTLY_GENERATED.items())
def test_partly_generated_sections_say_so_and_match_their_data(rel, script):
    from conftest import load_script
    mod = load_script(script)
