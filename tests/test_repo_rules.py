# --- workflows: every action pinned to a full commit SHA, every job has a timeout or is short ---

WORKFLOWS = sorted(glob.glob(os.path.join(ROOT, ".github", "workflows", "*.yml")))


@pytest.mark.parametrize("path", WORKFLOWS, ids=os.path.basename)
def test_actions_are_pinned_to_commit_shas(path):
    for line in open(path, encoding="utf-8"):
        m = re.search(r"uses:\s*([^\s#]+)", line)
        if not m or m.group(1).startswith("./"):
            continue
        ref = m.group(1).split("@")
        assert len(ref) == 2 and re.fullmatch(r"[0-9a-f]{40}", ref[1]), f"not SHA-pinned: {m.group(1)}"
        assert "#" in line, f"add the version as a comment: {line.strip()}"


@pytest.mark.parametrize("path", WORKFLOWS, ids=os.path.basename)
def test_workflows_parse_and_declare_permissions(path):
    doc = yaml.safe_load(open(path, encoding="utf-8"))
    assert "permissions" in doc, "top-level permissions keep the default token least-privilege"


def test_every_workflow_pins_the_same_cosign():
    """ci.yml checks builds.yml's signing flags on the cosign it installs, so both (and
    release.yml) must install the same one, named, not the installer's moving default."""
    found = {}
    for path in WORKFLOWS:
        for job in (yaml.safe_load(open(path, encoding="utf-8")).get("jobs") or {}).values():
            for step in job.get("steps", []):
                if "sigstore/cosign-installer@" in step.get("uses", ""):
                    found[os.path.basename(path)] = (step.get("with") or {}).get("cosign-release")
    assert {"builds.yml", "ci.yml", "release.yml"} <= set(found)
    assert None not in found.values(), f"set cosign-release: {found}"
    assert len(set(found.values())) == 1, f"one cosign version everywhere: {found}"


def test_every_workflow_pins_the_same_chainctl():
    """setup-chainctl installs `latest` unless told otherwise, right before it logs into
    the org: name one version (an exact release, not `latest`) everywhere."""
    found = {}
    for path in WORKFLOWS:
        for job in (yaml.safe_load(open(path, encoding="utf-8")).get("jobs") or {}).values():
            for step in job.get("steps", []):
                if "chainguard-dev/setup-chainctl@" in step.get("uses", ""):
                    found.setdefault(os.path.basename(path), set()).add(
                        str((step.get("with") or {}).get("version", "")))
    assert {"ci.yml", "builds.yml", "update.yml"} <= set(found)
    versions = set().union(*found.values())
    assert len(versions) == 1, f"one chainctl version everywhere: {found}"
    [v] = versions
    assert re.fullmatch(r"\d+\.\d+\.\d+", v), f"an exact chainctl release, not {v!r}"


# --- the VM tests (fips-kernel.yml, rke2.yml): every download pinned, every host allowed ---

GITHUB_DIR = os.path.join(ROOT, ".github")
VM_SCRIPTS = sorted(glob.glob(os.path.join(GITHUB_DIR, "*vm*.sh")))


@pytest.mark.parametrize("path", VM_SCRIPTS, ids=os.path.basename)
def test_vm_scripts_check_every_download_by_sha256(path):
    text = open(path, encoding="utf-8").read()
    for name in re.findall(r"^(\w+)_VERSION=", text, re.M):
        assert re.search(rf"^{name}_\w*SHA256=[0-9a-f]{{64}}$", text, re.M), f"{name}_VERSION has no pinned SHA256"
    curls = len(re.findall(r"\bcurl\b", text))
    checks = len(re.findall(r"sha256sum -c", text))
    assert curls <= checks, f"{curls} downloads but {checks} sha256sum checks: check each file you fetch"


def test_blocking_vm_workflows_allow_the_hosts_their_scripts_download_from():
    for wf in WORKFLOWS:
        text = open(wf, encoding="utf-8").read()
        if "egress-policy: block" not in text:
            continue
        allowed = set(re.findall(r"^\s+([\w.*-]+:\d+)$", text, re.M))
        for script in sorted(set(re.findall(r"\.github/([\w-]+\.sh)", text))):
            body = open(os.path.join(GITHUB_DIR, script), encoding="utf-8").read()
            if "vm-lib.sh" in body:
                body += open(os.path.join(GITHUB_DIR, "vm-lib.sh"), encoding="utf-8").read()
            for host in set(re.findall(r"https://([\w.-]+)/", body)):
                ok = f"{host}:443" in allowed or any(
                    a.startswith("*.") and host.endswith(a[1:].rsplit(":", 1)[0]) for a in allowed)
                assert ok, f"{os.path.basename(wf)} blocks {host}, which {script} downloads from"


